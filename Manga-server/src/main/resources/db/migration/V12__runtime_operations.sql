CREATE TABLE manga_model_call_ledger (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '模型调用账本主键',
    call_id CHAR(36) NOT NULL COMMENT '单次 Model.stream 订阅唯一标识',
    run_id CHAR(36) NOT NULL COMMENT '所属 Run',
    step_id CHAR(36) NOT NULL COMMENT '所属 Step',
    owner_epoch BIGINT NOT NULL COMMENT '开始调用时的围栏代次',
    config_id BIGINT NOT NULL COMMENT '冻结模型配置主键，不包含凭据',
    model_name VARCHAR(160) NOT NULL COMMENT '冻结模型名称',
    blueprint_fingerprint CHAR(64) NOT NULL COMMENT '冻结 Blueprint 指纹',
    status VARCHAR(16) NOT NULL COMMENT 'STARTED SUCCEEDED FAILED CANCELLED UNKNOWN',
    usage_reported BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否收到供应商用量，非正常完成时可能为部分用量',
    input_tokens BIGINT NULL COMMENT '累计输入 token，空表示未报告',
    output_tokens BIGINT NULL COMMENT '累计输出 token，包含计费推理输出',
    cached_tokens BIGINT NULL COMMENT '输入 token 中命中缓存的子集',
    reasoning_tokens BIGINT NULL COMMENT '输出 token 中推理子集，仅诊断不重复计价',
    cache_creation_tokens BIGINT NULL COMMENT '额外缓存创建 token，非零时费用未定',
    tool_use_prompt_tokens BIGINT NULL COMMENT '额外工具提示 token，非零时费用未定',
    input_price DECIMAL(20,8) NULL COMMENT '输入 USD 每百万 token，受理时冻结',
    cached_input_price DECIMAL(20,8) NULL COMMENT '缓存输入 USD 每百万 token，受理时冻结',
    output_price DECIMAL(20,8) NULL COMMENT '输出 USD 每百万 token，受理时冻结',
    reserved_usd DECIMAL(20,8) NOT NULL COMMENT '规划预留 USD，失败不退款',
    calculated_usd DECIMAL(20,8) NULL COMMENT '已报告用量计算额，非供应商账单；空为未知或未定价',
    settled_usd DECIMAL(20,8) NULL COMMENT '管理员核对账单后的 USD，空为未对账',
    settled_by BIGINT NULL COMMENT '认证对账管理员主键',
    settled_at TIMESTAMP(6) NULL COMMENT '对账确认时间，UTC',
    settlement_note VARCHAR(500) NULL COMMENT '账单编号或对账依据，不保存凭据',
    failure_type VARCHAR(160) NULL COMMENT '失败异常类型，不保存异常消息',
    started_at TIMESTAMP(6) NOT NULL COMMENT '调用受理时间，应用按 UTC 写入',
    expires_at TIMESTAMP(6) NOT NULL COMMENT '请求硬截止及容量租约到期时间',
    finished_at TIMESTAMP(6) NULL COMMENT '调用结算或标记未知的时间',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by VARCHAR(128) NOT NULL COMMENT '创建操作者',
    updated_by VARCHAR(128) NOT NULL COMMENT '更新操作者',
    PRIMARY KEY (id),
    CONSTRAINT uk_model_call UNIQUE (call_id),
    CONSTRAINT ck_model_call_status CHECK (status IN ('STARTED','SUCCEEDED','FAILED','CANCELLED','UNKNOWN')),
    INDEX idx_model_call_run (run_id, id),
    INDEX idx_model_call_gate (config_id, status, expires_at),
    INDEX idx_model_call_quota (config_id, started_at),
    INDEX idx_model_call_overview (started_at, status),
    INDEX idx_model_call_recovery (status, expires_at)
) COMMENT = '模型请求调用、冻结费率和已报告用量账本，不存提示词或凭据';

CREATE TABLE manga_provider_call_gate (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '门禁主键',
    config_id BIGINT NOT NULL COMMENT '每个配置跨实例共享的保护键',
    window_started_at TIMESTAMP(6) NOT NULL COMMENT '固定分钟窗口开始时间，应用按 UTC 写入',
    window_requests INT NOT NULL COMMENT '窗口受理次数',
    consecutive_failures INT NOT NULL COMMENT '连续可重试故障数',
    open_until TIMESTAMP(6) NULL COMMENT '熔断截止，空表示闭合',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by VARCHAR(128) NOT NULL COMMENT '创建操作者',
    updated_by VARCHAR(128) NOT NULL COMMENT '更新操作者',
    PRIMARY KEY (id),
    CONSTRAINT uk_provider_call_gate UNIQUE (config_id)
) COMMENT = '模型配置维度跨实例熔断、速率与规划配额门禁';

CREATE TABLE manga_creative_run_archive (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '归档副本主键',
    run_id CHAR(36) NOT NULL COMMENT '已终态且已完成投影的 Run',
    schema_version INT NOT NULL COMMENT '归档格式版本',
    payload_json LONGTEXT NOT NULL COMMENT '含用户内容的只读审计副本，仅管理员导出',
    sha256 CHAR(64) NOT NULL COMMENT '原始 UTF-8 内容 SHA-256',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by VARCHAR(128) NOT NULL COMMENT '创建操作者',
    updated_by VARCHAR(128) NOT NULL COMMENT '更新操作者',
    PRIMARY KEY (id),
    CONSTRAINT uk_creative_run_archive UNIQUE (run_id)
) COMMENT = '保留在线来源的无损审计归档，不代替数据库与媒体对象备份';
